'use strict';
const assert=require('node:assert/strict');
module.exports=async function careerFlow(p){
  p.setDefaultTimeout(7000);
  const company='合成公司甲', position='合成运营岗位', name='合成方向母版', content='隔离测试正文：整理合成需求并核对交付记录。', date='2026-05-18';
  const dialog=p.locator('.resume-dialog[open]');
  const button=(scope,name)=>scope.getByRole('button',{name,exact:true});
  const library=()=>p.locator('[data-job-tab="library"]').click();
  const jobResume=p.locator('#job-panel-library [data-job-resume-id]');
  const status=p.locator('#job-panel-library .job-status-select');
  const records=()=>p.evaluate(()=>({
    jobs:JSON.parse(localStorage.getItem('careerWorkbench.jobs.v1')),
    versions:JSON.parse(localStorage.getItem('careerWorkbench.jobsToolkit.v1')).resumeVersions
  }));
  await p.locator('#add-job-button').click();
  await p.locator('#company').fill(company);
  await p.locator('#position').fill(position);
  await p.locator('#job-direction').fill('其他');
  await p.locator('#status').selectOption('准备投递');
  await p.locator('#job-form [type=submit]').click();
  await p.locator('#job-dialog').waitFor({state:'hidden'});
  await p.locator('[data-job-tab="profile"]').click();
  await p.locator('#profile-education').fill('合成本科学历');
  await button(p,'保存我的求职档案').click();
  await p.locator('#job-resume-library').click();
  await dialog.getByLabel('简历名称',{exact:true}).fill(name);
  await dialog.getByLabel(/^简历完整正文/).fill(content);
  await dialog.getByLabel(/^我确认内容/).check();
  await button(dialog,'保存基础版本').click();
  assert.match(await dialog.locator('.resume-feedback').innerText(),/保存成功/);
  await button(dialog,'关闭').click();
  await library();
  const first=await records();
  assert.equal(first.jobs.length,1);assert.equal(first.versions.length,1);
  const id=first.jobs[0].id,version=first.versions[0].id;
  assert.ok(id && version);assert.equal(first.versions[0].content,content);
  await jobResume.click();
  await dialog.getByLabel('选择/更换简历').selectOption(version);
  assert.equal(await dialog.getByLabel('当前岗位准备投递的完整正文').inputValue(),content);
  await dialog.getByLabel(/^我确认内容/).check();
  await button(dialog,'保存本岗位准备使用的简历').click();
  assert.match(await dialog.locator('.resume-feedback').innerText(),/尚未标记投递/);
  const linked=(await records()).jobs[0];assert.equal(linked.resumeDraft.resumeVersionId,version);assert.equal(linked.status,'准备投递');assert.equal((linked.applicationResumeSnapshots||[]).length,0);
  await dialog.getByLabel('实际投递日期').fill(date);
  let confirmation='';
  p.once('dialog',async d=>{confirmation=d.message();await d.accept()});
  await button(dialog,'确认已投递并保存快照').click();
  assert.match(confirmation,/确实已使用这份内容投递/);
  assert.match(await dialog.locator('.resume-feedback').innerText(),/快照已保存/);
  const applied=(await records()).jobs[0];assert.equal(applied.status,'已投递');assert.equal(applied.applicationDate,date);
  assert.equal(applied.applicationResumeSnapshots.length,1);
  const snapshot=applied.applicationResumeSnapshots[0];
  assert.ok(snapshot.id && snapshot.recordedAt);
  assert.deepEqual([snapshot.company,snapshot.position,snapshot.jobId,snapshot.resumeVersionId,snapshot.resumeDraftId,snapshot.content,snapshot.appliedAt,snapshot.confirmedActuallySent],[company,position,id,version,linked.resumeDraft.id,content,date,true]);
  await button(dialog,'关闭').click();
  await status.selectOption('HR沟通');
  const before=await records();assert.equal(before.jobs[0].status,'HR沟通');assert.deepEqual(before.jobs[0].applicationResumeSnapshots,[snapshot]);
  await p.reload();await p.locator('[data-module="找工作"]').click();await library();
  assert.deepEqual(await records(),before);
  assert.equal(await status.inputValue(),'HR沟通');
  assert.equal(await jobResume.getAttribute('data-job-resume-id'),id);
  await jobResume.click();
  assert.equal(await dialog.getByLabel('选择/更换简历').inputValue(),version);
  const history=dialog.locator('details').filter({has:dialog.page().locator('summary',{hasText:date+'｜'+name})});
  await history.locator('summary').click();
  assert.equal(await history.locator('textarea[readonly]').inputValue(),content);
};
